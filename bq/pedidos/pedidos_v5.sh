    a=c.setdefault(k,[0,0]); a[0]+=1; a[1]+=float(r.get('PZS_ASIG') or 0)
print('Traslados vencidos sin salida (tienda-OC, pzs) por TR_CERRADO x OC:')
for k,v in sorted(c.items()): print(k, v[0], int(v[1]))
